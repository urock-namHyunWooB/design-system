// Tailwind CSS 설정 생성 스크립트
import { register } from "@tokens-studio/sd-transforms";
import StyleDictionary from "style-dictionary";
import fs from "fs";

console.log("🎨 Building Tailwind Config...\n");

register(StyleDictionary);

const sd = new StyleDictionary({
  source: ["default-token.json"],
  preprocessors: ["tokens-studio"],
  platforms: {
    js: {
      transformGroup: "js",
      buildPath: "build/tailwind/",
      files: [
        {
          destination: "tokens.js",
          format: "javascript/module-flat",
        },
      ],
    },
  },
});

// build 폴더가 없으면 생성
if (!fs.existsSync("build")) {
  fs.mkdirSync("build", { recursive: true });
}
if (!fs.existsSync("build/tailwind")) {
  fs.mkdirSync("build/tailwind", { recursive: true });
}

await sd.cleanAllPlatforms();
await sd.buildAllPlatforms();

// Tailwind 설정 파일 생성
const tokensModule = await import("./build/tailwind/tokens.js");
const tokens = tokensModule.default;

// 토큰을 Tailwind 테마 구조로 변환
const tailwindConfig = {
  theme: {
    extend: {
      colors: {},
      spacing: {},
      fontSize: {},
      fontWeight: {},
      lineHeight: {},
      letterSpacing: {},
      borderRadius: {},
      boxShadow: {},
    },
  },
};

// 토큰을 카테고리별로 분류
Object.entries(tokens).forEach(([key, value]) => {
  const lowerKey = key.toLowerCase();

  if (
    lowerKey.includes("color") ||
    lowerKey.includes("blue") ||
    lowerKey.includes("gray") ||
    lowerKey.includes("red") ||
    lowerKey.includes("green")
  ) {
    // Color 토큰
    const colorName = key.replace(/^color-/, "").replace(/-/g, ".");
    tailwindConfig.theme.extend.colors[colorName] = value;
  } else if (lowerKey.includes("spacing") || lowerKey.includes("space")) {
    // Spacing 토큰
    const spacingName = key.replace(/^spacing-/, "");
    tailwindConfig.theme.extend.spacing[spacingName] = value;
  } else if (lowerKey.includes("font-size") || lowerKey.includes("fontsize")) {
    // Font Size 토큰
    const fontSizeName = key.replace(/^font-size-/, "");
    tailwindConfig.theme.extend.fontSize[fontSizeName] = value;
  } else if (
    lowerKey.includes("font-weight") ||
    lowerKey.includes("fontweight")
  ) {
    // Font Weight 토큰
    const fontWeightName = key.replace(/^font-weight-/, "");
    tailwindConfig.theme.extend.fontWeight[fontWeightName] = value;
  } else if (
    lowerKey.includes("line-height") ||
    lowerKey.includes("lineheight")
  ) {
    // Line Height 토큰
    const lineHeightName = key.replace(/^line-height-/, "");
    tailwindConfig.theme.extend.lineHeight[lineHeightName] = value;
  } else if (
    lowerKey.includes("letter-spacing") ||
    lowerKey.includes("letterspacing")
  ) {
    // Letter Spacing 토큰
    const letterSpacingName = key.replace(/^letter-spacing-/, "");
    tailwindConfig.theme.extend.letterSpacing[letterSpacingName] = value;
  } else if (
    lowerKey.includes("border-radius") ||
    lowerKey.includes("borderradius") ||
    lowerKey.includes("radius")
  ) {
    // Border Radius 토큰
    const radiusName = key
      .replace(/^border-radius-/, "")
      .replace(/^radius-/, "");
    tailwindConfig.theme.extend.borderRadius[radiusName] = value;
  } else if (lowerKey.includes("shadow") || lowerKey.includes("box-shadow")) {
    // Box Shadow 토큰
    const shadowName = key.replace(/^box-shadow-/, "").replace(/^shadow-/, "");
    tailwindConfig.theme.extend.boxShadow[shadowName] = value;
  }
});

// tailwind.config.js 생성
const configContent = `// Generated by design-token build script
// Do not edit manually

export default ${JSON.stringify(tailwindConfig, null, 2)};

// CommonJS export for compatibility
module.exports = ${JSON.stringify(tailwindConfig, null, 2)};
`;

fs.writeFileSync("build/tailwind/tailwind.config.js", configContent, "utf-8");

console.log("✅ Tailwind tokens generated at build/tailwind/tokens.js");
console.log(
  "✅ Tailwind config generated at build/tailwind/tailwind.config.js\n"
);
